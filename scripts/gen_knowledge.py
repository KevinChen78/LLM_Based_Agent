def build():
    root = {"version": 1, "passages": []}
    for pid, cat, title, content, source, tags in PASSAGES:
        root["passages"].append({
            "id": pid, "category": cat, "title": title,
            "content": content, "source": source, "tags": tags,
        })
    return root


if __name__ == "__main__":
    root = build()
    with open(PATH, "w", encoding="utf-8") as fh:
        json.dump(root, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    sys.stdout.buffer.write(
        ("knowledge.json written: {0} passages -> {1}\n".format(
            len(root["passages"]), PATH)).encode("utf-8"))
